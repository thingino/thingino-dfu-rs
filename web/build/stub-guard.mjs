/**
 * Refuse to bundle a page whose engine is the hand-made stub.
 *
 * `web/test/make-seam-stub.mjs` writes a stand-in for the generated glue so the
 * page can be driven with no wasm. That is exactly what the adapter and page
 * tests need, and exactly what must never leave the tree: a `dist` built from it
 * loads, looks finished, and refuses every operation with "this build has no
 * engine". The stub deletes the real `tdfu_wasm_bg.wasm` when it
 * replaces a real glue, so the two cannot be mixed by accident either.
 *
 * `TDFU_ALLOW_STUB=1` says the engine-less page is what was wanted - it is what
 * `cargo xtask web`'s seam error tells you to type, and what the Playwright
 * remote-mode driver builds with, since the daemon owns the bus there.
 */

import { readFile } from 'node:fs/promises';

/** The first line `make-seam-stub.mjs` writes. Kept in step by its own test. */
export const STUB_MARKER = '/* GENERATED by web/test/make-seam-stub.mjs - not the real engine.';

/** Is this glue text the stub rather than wasm-bindgen's output? */
export function isStubGlue(text) {
    return typeof text === 'string' && text.startsWith(STUB_MARKER);
}

/**
 * What to refuse a build over, or null when there is nothing to refuse.
 *
 * Pure over the two inputs so the decision can be pinned without running vite.
 *
 * @param {string|null} glueText  the contents of web/src/wasm/tdfu_wasm.js, or null
 * @param {boolean} allowStub     TDFU_ALLOW_STUB=1 was set
 * @returns {string|null}
 */
export function stubRefusal(glueText, allowStub) {
    if (!isStubGlue(glueText) || allowStub) return null;
    return (
        'web/src/wasm/tdfu_wasm.js is the seam stub, not the engine.\n' +
        '  A page built from it loads, reads v0.0.0-stub in the footer and refuses\n' +
        '  every operation. Build the engine with `cargo xtask web --release`, or\n' +
        '  set TDFU_ALLOW_STUB=1 if an engine-less page is what you want.'
    );
}

/** The vite plugin: check once, before anything is bundled. */
export function refuseStubEngine(gluePath) {
    return {
        name: 'tdfu-refuse-stub-engine',
        apply: 'build',
        async buildStart() {
            let text = null;
            try {
                text = await readFile(gluePath, 'utf8');
            } catch {
                // No glue at all is rollup's error to report, not this one's: it
                // names the import site, which is the file that needs it.
                return;
            }
            const refusal = stubRefusal(text, process.env.TDFU_ALLOW_STUB === '1');
            if (refusal) this.error(refusal);
            if (isStubGlue(text)) {
                this.warn('building with the seam stub: this page has no engine (TDFU_ALLOW_STUB=1)');
            }
        },
    };
}
