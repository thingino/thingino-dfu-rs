/**
 * Write a stand-in for the generated wasm-bindgen glue into web/src/wasm/.
 *
 * `cargo xtask web` puts the real `tdfu_wasm.js` there. This writes a hand-made
 * one implementing the same seam, so the page can be built and
 * driven with no wasm at all: the adapter and page tests use it, and so does the
 * Playwright remote-mode run, which never reaches the engine's USB paths
 * because the daemon owns the bus there.
 *
 * It refuses to overwrite the real glue - `cargo xtask web` writes a
 * `tdfu_wasm_bg.wasm` beside it - so running it after a build is a no-op you
 * have to force with --force. **--force deletes that wasm too**:
 * a stub glue beside a real engine builds a `dist` that loads, says
 * `v0.0.0-stub (stub)` in the footer and refuses every operation, which is the
 * one state here that looks shippable and is not. The glue also marks itself,
 * and `vite.config.js` refuses to build a page from a marked glue unless
 * TDFU_ALLOW_STUB=1 says that is what was wanted.
 *
 *   node web/test/make-seam-stub.mjs [--force]
 *
 * The engine it makes is scriptable from the page:
 *   globalThis.__TDFU_STUB__ = {
 *       devices: [...],       // what discover()/requestDevice() answer
 *       readSize: 4096,       // how many bytes read() returns
 *       failWith: 'NotDfu',   // every operation rejects with this kind
 *       failMessage: '...',   // and this message
 *       failInit: true,       // init() itself rejects: the page gets no engine
 *       calls: [],            // every call lands here as [name, id]
 *   }
 */

import { mkdir, writeFile, access, readFile, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'src', 'wasm');
const outFile = join(outDir, 'tdfu_wasm.js');
const wasmFile = join(outDir, 'tdfu_wasm_bg.wasm');
const variantRs = join(here, '..', '..', 'crates', 'tdfu-proto', 'src', 'variant.rs');
const force = process.argv.includes('--force');

/** The first line of a stub glue. `vite.config.js` looks for exactly this. */
export const STUB_MARKER = '/* GENERATED by web/test/make-seam-stub.mjs - not the real engine.';

/* The frozen wire table, read out of crates/tdfu-proto/src/variant.rs
 * rather than transcribed. A hand copy agreed with the wire table
 * on the day it was written and nothing kept it that way: appending a 60th
 * loader upstream would have left the browser rendering ordinal 59 as `unknown`
 * with every JS assertion still green, because they compared the copy against
 * itself. Reading the source means the drift cannot happen. */
export async function wireVariantNames(path) {
    const rust = await readFile(path, 'utf8');
    const count = rust.match(/pub const COUNT: u8 = (\d+);/);
    const table = rust.match(/static NAMES: \[&str; WireVariant::COUNT as usize\] = \[([\s\S]*?)\];/);
    if (!count || !table) {
        throw new Error(`${path}: no WireVariant::COUNT / NAMES table - has variant.rs been reshaped?`);
    }
    const names = [...table[1].matchAll(/"([^"]*)"/g)].map((m) => m[1]);
    if (names.length !== Number(count[1])) {
        throw new Error(`${path}: COUNT is ${count[1]} but NAMES holds ${names.length}`);
    }
    return names;
}

const NAMES = await wireVariantNames(variantRs);

const SOURCE = `${STUB_MARKER}
 *
 * A stand-in for wasm-bindgen's glue that implements the engine's JS seam
 * without any wasm. Every USB operation rejects unless the page scripts one
 * through globalThis.__TDFU_STUB__, so nothing here can be mistaken for a
 * working flasher.
 */

const NAMES = ${JSON.stringify(NAMES, null, 4).replace(/\n/g, '\n')};

function conf() { return (globalThis.__TDFU_STUB__ || {}); }

function fail(kind, message, recoverable) {
    const e = new Error(message);
    e.kind = kind;
    e.recoverable = !!recoverable;
    return e;
}

/* Nothing throws synchronously, per the seam. */
function refuse(what) {
    const c = conf();
    if (c.failWith) return Promise.reject(fail(c.failWith, c.failMessage || (what + ' failed'), false));
    return Promise.reject(fail('Unsupported', 'this build has no engine: ' + what + ' needs cargo xtask web', false));
}

/* Every call, as [name, id], for a test that has to prove WHICH device an
 * operation went to - an id the page kept across a re-enumeration is a dead
 * handle, and the only way to see the difference is to look at what was
 * passed. */
function record(what, id) {
    const c = conf();
    if (Array.isArray(c.calls)) c.calls.push([what, id]);
}

export default async function init() {
    if (conf().failInit) return Promise.reject(fail('Unsupported', 'the stub was told to fail init()', false));
    return {};
}

export function version() { return (conf().version || '0.0.0-stub') + ' (stub)'; }

export function variantNames() { return NAMES.slice(); }

export class Engine {
    constructor(sinks) {
        this.log = (sinks && sinks.log) || function () {};
        this.progress = (sinks && sinks.progress) || function () {};
        this.debug = false;
    }

    setDebug(on) {
        this.debug = !!on;
        this.log('debug logging ' + (this.debug ? 'on' : 'off'), 'debug');
    }

    _devices() { return conf().devices || []; }

    async requestDevice() {
        record('requestDevice', null);
        if (conf().failWith) return refuse('requestDevice');
        const d = this._devices();
        return d.length ? d[0] : null;
    }

    /* Listing can fail too: a Linux udev race, or a page with no usb permission
     * policy, and getDevices() rejects rather than answering an empty list. */
    async discover() {
        record('discover', null);
        if (conf().failWith) return refuse('discover');
        return this._devices().slice();
    }

    async detect(id) {
        record('detect', id);
        const d = this._devices().find((x) => x.id === id);
        if (!d || conf().failWith) return refuse('detect');
        return { variant: d.variant || 't31x', chip: d.chip || 'T31X', family: 'T31', dram: 'DDR2', evidence: 'stub', caveat: null };
    }

    /* Enough of a transfer to drive the page's bar and log routing. */
    async _transfer(phase, total) {
        this.progress(phase, 0, total);
        for (let done = 0; done < total; done += Math.max(1, Math.floor(total / 4))) {
            this.progress(phase, Math.min(done, total), total);
            await new Promise((r) => setTimeout(r, 1));
        }
        this.progress(phase, total, total);
    }

    async bootstrap(id, opts) {
        record('bootstrap', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('bootstrap');
        if ((opts.spl && !opts.uboot) || (!opts.spl && opts.uboot)) {
            return refuse('bootstrap');
        }
        await this._transfer('stage1', (opts.spl && opts.spl.length) || 4096);
        await this._transfer('u-boot', (opts.uboot && opts.uboot.length) || 4096);
        this.log('U-Boot is starting', 'info');
    }

    async write(id, opts) {
        record('write', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('write');
        await this._transfer('download', opts.image.length);
        this.log('DFU download complete', 'info');
        if (opts.verify) {
            await this._transfer('verify', opts.image.length);
            this.log('Verify OK: ' + opts.image.length + ' bytes match', 'info');
        }
    }

    async read(id, opts) {
        record('read', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('read');
        const size = (opts && opts.size) || conf().readSize || 4096;
        await this._transfer('upload', size);
        this.log('DFU upload complete: ' + size + ' bytes', 'info');
        return new Uint8Array(size);
    }

    async verify(id, opts) {
        record('verify', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('verify');
        await this._transfer('verify', opts.image.length);
    }

    async erase(id) {
        record('erase', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('erase');
        await this._transfer('erase', 4096);
    }

    async reboot(id) {
        record('reboot', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('reboot');
        this.log('Reboot triggered', 'info');
    }

    async diag(id) {
        record('diag', id);
        if (conf().failWith || !this._devices().some((x) => x.id === id)) return refuse('diag');
        return conf().diagText || 'Chip: stub\\nSecure boot: disabled';
    }
}
`;

async function exists(path) {
    try {
        await access(path);
        return true;
    } catch {
        return false;
    }
}

/** Write the stub. Exported so a test can call it; run below when this is the script. */
export async function writeStub() {
    await mkdir(outDir, { recursive: true });
    const realWasm = await exists(wasmFile);
    if (!force && realWasm) {
        console.log('make-seam-stub: real glue present, leaving it alone (--force to replace)');
        return false;
    }
    if (!force && (await exists(outFile))) {
        const current = await readFile(outFile, 'utf8');
        if (!current.startsWith(STUB_MARKER)) {
            console.error('make-seam-stub: ' + outFile + ' was not written by this script; refusing');
            process.exitCode = 1;
            return false;
        }
    }
    await writeFile(outFile, SOURCE);
    console.log('make-seam-stub: wrote ' + outFile);
    /* The engine goes with the glue. Leaving a real tdfu_wasm_bg.wasm beside a
     * stub tdfu_wasm.js is the one half-built state that looks finished: vite
     * bundles both, dist loads, and every operation answers "this build has no
     * engine". `cargo xtask web` writes both again together. */
    if (realWasm) {
        await rm(wasmFile, { force: true });
        console.log('make-seam-stub: removed ' + wasmFile + ' - run `cargo xtask web` for a real page');
    }
    return true;
}

/* Importing this module must not write anything: the adapter test reads
 * wireVariantNames() out of it to compare the stub's table against the wire
 * table's own source. Only running it as a script writes the glue. */
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
    await writeStub();
}
